//! Where uploaded files are kept between `mode=file` and `mode=import`.
//!
//! Methods are synchronous; the server calls them on tokio's blocking
//! thread pool. Names passed to a storage are always cleaned by
//! [`sanitize_name`] first: relative, `/`-separated, without `..`.

use std::collections::HashMap;
use std::fs::{self, File, OpenOptions};
use std::io::{self, Cursor, Read, Seek, Write};
use std::path::{Path, PathBuf};
use std::sync::Mutex;

/// A readable, seekable file from a storage.
pub trait ReadSeek: Read + Seek + Send {}
impl<T: Read + Seek + Send> ReadSeek for T {}

/// Keeps uploaded files per session.
pub trait FileStorage: Send + Sync + 'static {
    /// Appends `data` to `name`, creating it if needed; returns the new size.
    fn append(&self, session: &str, name: &str, data: &[u8]) -> io::Result<u64>;
    /// Opens `name` for reading.
    fn open(&self, session: &str, name: &str) -> io::Result<Box<dyn ReadSeek>>;
    /// Size of `name`, or `None` if it does not exist.
    fn size(&self, session: &str, name: &str) -> io::Result<Option<u64>>;
    /// Deletes `name` if it exists.
    fn remove(&self, session: &str, name: &str) -> io::Result<()>;
    /// Names of all files of a session.
    fn list(&self, session: &str) -> io::Result<Vec<String>>;
    /// Deletes all files of a session.
    fn clear(&self, session: &str) -> io::Result<()>;
}

/// Cleans a file name from a request or a zip archive.
///
/// Backslashes become `/`; empty and `.` components are dropped. Absolute
/// paths, drive letters, `..`, control characters and names over 255 bytes
/// per component are rejected.
///
/// ```
/// use commerceml_exchange::storage::sanitize_name;
///
/// assert_eq!(sanitize_name("import_files\\ab\\x.jpg"), Some("import_files/ab/x.jpg".into()));
/// assert_eq!(sanitize_name("../etc/passwd"), None);
/// assert_eq!(sanitize_name("/abs.xml"), None);
/// ```
pub fn sanitize_name(name: &str) -> Option<String> {
    let name = name.replace('\\', "/");
    if name.starts_with('/') || name.contains(':') || name.chars().any(char::is_control) {
        return None;
    }
    let mut parts = Vec::new();
    for part in name.split('/') {
        match part {
            "" | "." => {}
            ".." => return None,
            p if p.len() > 255 => return None,
            p => parts.push(p),
        }
    }
    if parts.is_empty() {
        return None;
    }
    Some(parts.join("/"))
}

/// Session tokens are generated by the server, but check them anyway
/// before using them as directory names.
fn check_session(session: &str) -> io::Result<()> {
    if !session.is_empty()
        && session
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
    {
        Ok(())
    } else {
        Err(io::Error::new(io::ErrorKind::InvalidInput, "bad session id"))
    }
}

fn check_name(name: &str) -> io::Result<()> {
    if sanitize_name(name).as_deref() == Some(name) {
        Ok(())
    } else {
        Err(io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("bad file name {name:?}"),
        ))
    }
}

/// Files on disk: `<root>/<session>/<name>`.
#[derive(Debug, Clone)]
pub struct FsStorage {
    root: PathBuf,
}

impl FsStorage {
    /// Uses `root` as the base directory; it is created if missing.
    pub fn new(root: impl Into<PathBuf>) -> io::Result<Self> {
        let root = root.into();
        fs::create_dir_all(&root)?;
        Ok(Self { root })
    }

    /// The directory of a session, e.g. for handlers that want paths.
    pub fn session_dir(&self, session: &str) -> io::Result<PathBuf> {
        check_session(session)?;
        Ok(self.root.join(session))
    }

    fn path(&self, session: &str, name: &str) -> io::Result<PathBuf> {
        check_name(name)?;
        Ok(self.session_dir(session)?.join(Path::new(name)))
    }
}

impl FileStorage for FsStorage {
    fn append(&self, session: &str, name: &str, data: &[u8]) -> io::Result<u64> {
        let path = self.path(session, name)?;
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent)?;
        }
        let mut f = OpenOptions::new().create(true).append(true).open(&path)?;
        f.write_all(data)?;
        Ok(f.metadata()?.len())
    }

    fn open(&self, session: &str, name: &str) -> io::Result<Box<dyn ReadSeek>> {
        Ok(Box::new(File::open(self.path(session, name)?)?))
    }

    fn size(&self, session: &str, name: &str) -> io::Result<Option<u64>> {
        match fs::metadata(self.path(session, name)?) {
            Ok(m) if m.is_file() => Ok(Some(m.len())),
            Ok(_) => Ok(None),
            Err(e) if e.kind() == io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(e),
        }
    }

    fn remove(&self, session: &str, name: &str) -> io::Result<()> {
        match fs::remove_file(self.path(session, name)?) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        }
    }

    fn list(&self, session: &str) -> io::Result<Vec<String>> {
        fn walk(dir: &Path, prefix: &str, out: &mut Vec<String>) -> io::Result<()> {
            for entry in fs::read_dir(dir)? {
                let entry = entry?;
                let name = entry.file_name().to_string_lossy().into_owned();
                let rel = if prefix.is_empty() {
                    name
                } else {
                    format!("{prefix}/{name}")
                };
                if entry.file_type()?.is_dir() {
                    walk(&entry.path(), &rel, out)?;
                } else {
                    out.push(rel);
                }
            }
            Ok(())
        }
        let dir = self.session_dir(session)?;
        let mut out = Vec::new();
        match walk(&dir, "", &mut out) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => return Err(e),
            _ => {}
        }
        out.sort();
        Ok(out)
    }

    fn clear(&self, session: &str) -> io::Result<()> {
        match fs::remove_dir_all(self.session_dir(session)?) {
            Err(e) if e.kind() != io::ErrorKind::NotFound => Err(e),
            _ => Ok(()),
        }
    }
}

/// Files in memory, for tests and small deployments.
#[derive(Debug, Default)]
pub struct MemoryStorage {
    files: Mutex<HashMap<(String, String), Vec<u8>>>,
}

impl MemoryStorage {
    /// An empty storage.
    pub fn new() -> Self {
        Self::default()
    }

    fn files(&self) -> std::sync::MutexGuard<'_, HashMap<(String, String), Vec<u8>>> {
        self.files
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner)
    }
}

impl FileStorage for MemoryStorage {
    fn append(&self, session: &str, name: &str, data: &[u8]) -> io::Result<u64> {
        check_session(session)?;
        check_name(name)?;
        let mut files = self.files();
        let f = files.entry((session.to_owned(), name.to_owned())).or_default();
        f.extend_from_slice(data);
        Ok(f.len() as u64)
    }

    fn open(&self, session: &str, name: &str) -> io::Result<Box<dyn ReadSeek>> {
        let files = self.files();
        let data = files
            .get(&(session.to_owned(), name.to_owned()))
            .ok_or_else(|| io::Error::new(io::ErrorKind::NotFound, format!("{name} not found")))?;
        Ok(Box::new(Cursor::new(data.clone())))
    }

    fn size(&self, session: &str, name: &str) -> io::Result<Option<u64>> {
        Ok(self
            .files()
            .get(&(session.to_owned(), name.to_owned()))
            .map(|f| f.len() as u64))
    }

    fn remove(&self, session: &str, name: &str) -> io::Result<()> {
        self.files().remove(&(session.to_owned(), name.to_owned()));
        Ok(())
    }

    fn list(&self, session: &str) -> io::Result<Vec<String>> {
        let mut names: Vec<String> = self
            .files()
            .keys()
            .filter(|(s, _)| s == session)
            .map(|(_, n)| n.clone())
            .collect();
        names.sort();
        Ok(names)
    }

    fn clear(&self, session: &str) -> io::Result<()> {
        self.files().retain(|(s, _), _| s != session);
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitizing() {
        assert_eq!(sanitize_name("a/./b//c.xml").as_deref(), Some("a/b/c.xml"));
        for bad in ["", "/", "..", "a/../b", "C:\\x", "a\0b", "\\\\server\\share"] {
            assert_eq!(sanitize_name(bad), None, "{bad:?}");
        }
        assert_eq!(sanitize_name(&"x".repeat(256)), None);
        assert!(check_session("abc-123_X").is_ok());
        assert!(check_session("../x").is_err());
        assert!(check_session("").is_err());
    }

    fn exercise(s: &dyn FileStorage) {
        assert_eq!(s.append("s1", "a/b.xml", b"12").unwrap(), 2);
        assert_eq!(s.append("s1", "a/b.xml", b"34").unwrap(), 4);
        s.append("s1", "c.xml", b"x").unwrap();
        s.append("s2", "c.xml", b"y").unwrap();
        let mut buf = String::new();
        s.open("s1", "a/b.xml").unwrap().read_to_string(&mut buf).unwrap();
        assert_eq!(buf, "1234");
        assert_eq!(s.size("s1", "a/b.xml").unwrap(), Some(4));
        assert_eq!(s.size("s1", "nope").unwrap(), None);
        assert_eq!(s.list("s1").unwrap(), ["a/b.xml", "c.xml"]);
        s.remove("s1", "c.xml").unwrap();
        s.remove("s1", "c.xml").unwrap();
        assert_eq!(s.list("s1").unwrap(), ["a/b.xml"]);
        s.clear("s1").unwrap();
        s.clear("s1").unwrap();
        assert_eq!(s.list("s1").unwrap().len(), 0);
        assert_eq!(s.list("s2").unwrap(), ["c.xml"]);
        assert!(s.append("s1", "../x", b"").is_err());
        assert!(s.append("../s", "x", b"").is_err());
        assert!(s.open("s1", "missing").is_err());
    }

    #[test]
    fn memory_storage() {
        exercise(&MemoryStorage::new());
    }

    #[test]
    fn fs_storage() {
        let dir = std::env::temp_dir().join(format!("cml-fs-storage-{}", std::process::id()));
        let s = FsStorage::new(&dir).unwrap();
        exercise(&s);
        assert!(s.session_dir("s2").unwrap().starts_with(&dir));
        fs::remove_dir_all(&dir).unwrap();
    }
}
